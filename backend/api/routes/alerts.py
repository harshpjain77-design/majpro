"""Threat detection and alert evaluation API endpoints."""

from typing import List, Optional
from fastapi import APIRouter, Depends, Query

from backend.api.dependencies import storage_sink, verify_api_key
from backend.detection.config import default_config
from backend.detection.engine import DetectionEngine
from backend.detection.schemas import Alert

router = APIRouter(
    prefix="/api/v1/detection",
    tags=["Detection"],
    dependencies=[Depends(verify_api_key)],
)

detection_engine = DetectionEngine(config=default_config)


@router.get("/rules")
async def list_detection_rules():
    """List all registered deterministic threat detection rules."""
    return {"rules": detection_engine.get_rules_metadata()}


@router.post("/evaluate", response_model=List[Alert])
async def evaluate_detection(
    start_time: Optional[str] = Query(None, description="Start time for evaluated window"),
    end_time: Optional[str] = Query(None, description="End time for evaluated window"),
    limit: int = Query(1000, ge=1, le=5000, description="Max events to pull for evaluation"),
) -> List[Alert]:
    """Trigger deterministic detection rules on stored events and return generated alerts."""
    return detection_engine.evaluate_from_repository(
        repo=storage_sink,
        start_time=start_time,
        end_time=end_time,
        limit=limit,
    )


# Standalone alerts query endpoints directly supported at /api/v1/alerts
alerts_direct_router = APIRouter(
    prefix="/api/v1/alerts",
    tags=["Alerts"],
    dependencies=[Depends(verify_api_key)],
)


@alerts_direct_router.get("", response_model=List[Alert])
async def get_alerts(
    start_time: Optional[str] = Query(None, description="Filter alerts after start timestamp"),
    end_time: Optional[str] = Query(None, description="Filter alerts before end timestamp"),
    severity: Optional[str] = Query(None, description="Filter by severity"),
    limit: int = Query(100, ge=1, le=1000, description="Maximum alerts to retrieve"),
) -> List[Alert]:
    """Retrieve real alerts generated by the detection engine from stored events."""
    alerts = detection_engine.evaluate_from_repository(
        repo=storage_sink,
        start_time=start_time,
        end_time=end_time,
        limit=limit,
    )
    if severity and severity.upper() != "ALL":
        alerts = [a for a in alerts if a.severity.lower() == severity.lower()]
    return alerts


@alerts_direct_router.get("/{alert_id}", response_model=Alert)
async def get_alert_by_id(alert_id: str) -> Alert:
    """Retrieve a single alert by its alert ID."""
    from fastapi import HTTPException, status
    alerts = detection_engine.evaluate_from_repository(repo=storage_sink, limit=2000)
    for a in alerts:
        if a.alert_id == alert_id:
            return a
    raise HTTPException(
        status_code=status.HTTP_404_NOT_FOUND,
        detail=f"Alert with ID '{alert_id}' not found.",
    )

